#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Linked market news ("סקירה חדשותית") collector for the scanner site.

Runs inside the existing refresh workflow. Regenerates news_latest.json at
most once an hour (a manual workflow_dispatch run always rescans); ordinary
15-minute refreshes reuse the committed file, so the tab updates hourly
exactly as the user asked.

Design rules (from the user's spec):
  * Headlines, links, publish times and opening lines come straight from the
    outlets' own RSS feeds. Nothing is rewritten or generated by a model.
  * Opening lines are shown only when the feed supplies them; otherwise the
    item appears without one. Openings are trimmed to ~220 characters.
  * Only fresh items are kept (per-section windows below). When nothing
    fresh exists the section renders an honest empty state - never stale
    backfill.
  * Same story from several outlets is deduped by title similarity, keeping
    the item whose source supplies an opening.
  * Nothing about the user's portfolio is read or used.

No secrets or paid services are needed - public RSS only.
"""
import json
import os
import re
import sys
import html as htmlmod
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from datetime import datetime, timedelta, timezone
from email.utils import parsedate_to_datetime
from zoneinfo import ZoneInfo

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
OUT_FILE = os.path.join(BASE_DIR, "news_latest.json")
JER = ZoneInfo("Asia/Jerusalem")
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/142 Safari/537.36"

REFRESH_MINUTES = 55          # regenerate at most this often (hourly cadence)
WINDOWS_H = {"us": 14, "il": 20, "geo": 48}   # freshness windows per section
CAPS = {"us": 10, "il": 8, "geo": 2}
LEDE_MAX = 220

GN = "https://news.google.com/rss/search?q={q}&hl={hl}&gl={gl}&ceid={gl}:{ceid}"
FEEDS = [
    # section, url, fixed source (None = read <source> tag), feed supplies lede
    ("us", "https://www.cnbc.com/id/100003114/device/rss/rss.html", "CNBC", True),
    ("us", "http://feeds.marketwatch.com/marketwatch/topstories/", "MarketWatch", True),
    ("us", "https://www.ft.com/rss/home", "Financial Times", True),
    ("us", "http://feeds.bbci.co.uk/news/business/rss.xml", "BBC", True),
    ("us", "https://www.theguardian.com/uk/business/rss", "The Guardian", True),
    ("us", "https://seekingalpha.com/feed.xml", "Seeking Alpha", False),
    ("us", "https://www.globes.co.il/webservice/rss/rssfeeder.asmx/FeederNode?iID=1225", "גלובס", True),
    ("us", GN.format(q=urllib.parse.quote("stock market when:1d"), hl="en-US", gl="US", ceid="en"), None, False),
    ("il", "https://www.globes.co.il/webservice/rss/rssfeeder.asmx/FeederNode?iID=585", "גלובס", True),
    ("il", "https://www.globes.co.il/webservice/rss/rssfeeder.asmx/FeederNode?iID=2", "גלובס", True, "he"),
    ("il", "https://rss.walla.co.il/feed/112", "וואלה", True),
    ("il", GN.format(q=urllib.parse.quote("בורסה when:2d"), hl="he", gl="IL", ceid="he"), None, False),
    ("geo", GN.format(q=urllib.parse.quote('geopolitical OR war OR sanctions OR "middle east" when:2d'),
                      hl="en-US", gl="US", ceid="en"), None, False),
]

# English general-business feeds that must pass the market-headline filter.
KW_FILTERED = {"CNBC", "MarketWatch", "Financial Times", "BBC", "The Guardian", "Seeking Alpha"}
SA_NOISE = re.compile(r"earnings call (presentation|transcript)|- results -", re.I)

# General feeds (CNBC / MarketWatch top stories) carry politics and lifestyle;
# keep an item only when its headline is about markets.
MARKET_KW = re.compile(
    r"stock|market|nasdaq|s&p|dow jones|wall street|\bfed\b|interest rate|inflation|earnings|"
    r"treasur|bond|oil|crude|bitcoin|crypto|investor|rally|sell-?off|slump|surge|plunge|futures|"
    r"tariff|\bipo\b|shares|chip|semiconductor|big tech|recession|dollar|gold|\bgdp\b|\bcpi\b|"
    r"\betf\b|bull market|bear market|economy|jobs report", re.I)
NOT_MARKET_KW = re.compile(
    r"football|soccer|baseball|basketball|\bnfl\b|\bnba\b|tennis|golf|olympics|world cup|"
    r"bulldog|touchdown|quarterback|playoff|grand theft|\bgta\b", re.I)

# Geopolitics section: only headline-level outlets, so blog noise stays out.
GEO_SOURCES = {
    "reuters", "ap news", "associated press", "bloomberg", "cnbc", "bbc", "bbc news",
    "the guardian", "axios", "npr", "pbs", "cnn", "france 24", "financial times",
    "the new york times", "the wall street journal", "the economist", "al jazeera",
    "haaretz", "sky news", "abc news", "cbs news", "nbc news", "politico", "dw",
}


# Google News aggregates everything; only established outlets count toward the
# "important stories" bar. Smaller sites are fine as their own section feeds.
BIG_SOURCES = {
    "reuters", "ap news", "bloomberg", "cnbc", "bbc", "bbc news", "the guardian",
    "axios", "financial times", "the new york times", "the wall street journal",
    "yahoo finance", "marketwatch", "barron's", "investor's business daily",
    "cnn", "fortune", "the economist", "morningstar", "seeking alpha",
    "calcalist", "כלכליסט", "גלובס", "globes", "themarker", "דה מרקר",
    "ביזפורטל", "bizportal", "וואלה", "walla", "מעריב", "i24news", "כאן",
}

GEO_KW = re.compile(
    r"iran|israel|ukraine|russia|gaza|lebanon|houthi|middle east|hormuz|taiwan|"
    r"north korea|\bnato\b|ceasefire|missile|sanction|geopolitic|netanyahu|"
    r"\bstrike|\bwar\b|pentagon|hezbollah", re.I)
GEO_EXCLUDE = re.compile(
    r"civil war|world war|vietnam|star wars|drug war|console war|streaming war|"
    r"price war|cola war", re.I)


def http_get(url, timeout=20):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read()


def clean_text(s):
    s = re.sub(r"<[^>]+>", " ", s or "")
    s = htmlmod.unescape(s)
    return re.sub(r"\s+", " ", s).strip()


def trim_lede(desc):
    """The outlet's own opening lines, kept brief (~220 chars)."""
    s = clean_text(desc)
    if "•" in s and s.index("•") >= 40:
        s = s[:s.index("•")].strip()
    if len(s) > LEDE_MAX:
        s = s[:LEDE_MAX].rsplit(" ", 1)[0].rstrip(",;:—- ") + "…"
    return s or None


STOPWORDS = {
    "a", "an", "the", "in", "on", "at", "to", "for", "of", "and", "or",
    "as", "is", "are", "was", "were", "be", "been", "by", "with", "from",
    "that", "this", "it", "its", "his", "her", "their", "after", "before",
    "over", "under", "into", "about", "amid", "says", "said", "say",
    "what", "why", "how", "new", "latest", "update", "live", "briefing",
    "watch", "explainer", "analysis",
}


def _stem(w):
    # good-enough plural strip so "apps"/"app" and "alerts"/"alert" match
    if len(w) > 4 and w.endswith("es"):
        return w[:-2]
    if len(w) > 3 and w.endswith("s"):
        return w[:-1]
    return w


def content_tokens(toks):
    return {_stem(w) for w in toks} - STOPWORDS


def norm_title(t):
    t = re.sub(r"\s+-\s+[^-]{2,40}$", "", t or "")  # drop " - Source" suffix
    return set(re.findall(r"[a-z0-9\u0590-\u05ff]+", t.lower()))


def is_dup(toks, kept):
    for k in kept:
        if not toks or not k:
            continue
        j = len(toks & k) / max(1, len(toks | k))
        if j >= 0.6:
            return True
        # cross-outlet rewrite of the same story: many shared content words
        # (e.g. "air raid alert apps" vs "air raid warning app")
        shared = content_tokens(toks) & content_tokens(k)
        if len(shared) >= 4 and sum(1 for w in shared if len(w) >= 5) >= 2:
            return True
    return False


HE_MARKET_KW = re.compile(
    r"בורס|שוק ההון|מנייה|מניות|מדד|וול סטריט|נאסד|S&P|דולר|אירו|שקל|ריבית|אינפלצ|"
    r"אג\"?ח|נפט|זהב|ביטקוין|קריפטו|כלכל|דוחות|רווח|משקיע|תשואה|עסקה|הייטק|"
    r"סטארט.?אפ|בנק|נדל\"?ן|משכנת"
)


def parse_feed(url, fixed_source, has_lede):
    root = ET.fromstring(http_get(url))
    items = []
    for it in root.iter("item"):
        title = clean_text(it.findtext("title"))
        link = (it.findtext("link") or "").strip()
        pub_raw = (it.findtext("pubDate") or "").strip()
        if not title or not link or not pub_raw:
            continue
        try:
            pub = parsedate_to_datetime(pub_raw)
            if pub.tzinfo is None:
                pub = pub.replace(tzinfo=timezone.utc)
        except Exception:
            continue
        if fixed_source:
            source = fixed_source
        else:
            src = it.find("source")
            source = (src.text or "").strip() if src is not None else ""
            title = re.sub(r"\s+-\s+" + re.escape(source) + r"$", "", title) if source else title
        lede = trim_lede(it.findtext("description")) if has_lede else None
        items.append({"title": title, "url": link, "source": source or "מקור לא ידוע",
                      "published": pub.isoformat(), "lede": lede})
    return items


def main():
    force = "--force" in sys.argv
    try:
        old = json.load(open(OUT_FILE, encoding="utf-8"))
        gen = datetime.fromisoformat(old["generated_at"])
        if gen.tzinfo is None:
            gen = gen.replace(tzinfo=JER)
    except Exception:
        old, gen = None, None
    if old and gen and not force and datetime.now(JER) - gen < timedelta(minutes=REFRESH_MINUTES):
        print(f"KEEP news_latest.json (age {(datetime.now(JER) - gen).seconds // 60}m < hourly cadence)")
        return

    now = datetime.now(timezone.utc)
    ok, failed = [], []
    raw = {"us": [], "il": [], "geo": []}
    for feed in FEEDS:
        section, url, fixed_source, has_lede = feed[:4]
        kw = feed[4] if len(feed) > 4 else None
        try:
            items = parse_feed(url, fixed_source, has_lede)
            if fixed_source is None:
                for it in items:
                    it["_gn"] = True
            if kw == "he":
                for it in items:
                    it["_he_kw"] = True
            raw[section].extend(items)
            ok.append(fixed_source or "Google News")
            print(f"OK   [{section}] {fixed_source or 'GoogleNews'}: {len(items)} items")
        except Exception as e:
            failed.append(f"{fixed_source or url}: {e}")
            print(f"FAIL [{section}] {fixed_source or url}: {e}")

    if not ok:
        print("ALL FEEDS FAILED - keeping previous news_latest.json")
        return

    # Per-source caps keep Google News from flooding a section with whatever is
    # newest, and keep the lede-bearing outlets (CNBC / MarketWatch / Globes)
    # present in every refresh.
    SRC_CAPS = {"us": {"Google News": 3, "CNBC": 3, "MarketWatch": 2, "Financial Times": 2,
                       "BBC": 2, "The Guardian": 2, "Seeking Alpha": 1, "Investing.com": 1, "גלובס": 2},
                "il": {"Google News": 3, "גלובס": 4, "וואלה": 2},
                "geo": {"Google News": 2}}
    GN_SOURCES = set(SRC_CAPS["us"]) | {"Google News"}

    sections = {}
    kept_toks = []          # global: the same story never appears in two sections
    for sec, items in raw.items():
        window = timedelta(hours=WINDOWS_H[sec])
        per_src = {}
        out = []
        for it in sorted(items, key=lambda x: x["published"], reverse=True):
            pub = datetime.fromisoformat(it["published"])
            if now - pub.astimezone(timezone.utc) > window:
                continue
            t = it["title"]
            is_gn = it.get("_gn", False)
            if sec == "geo":
                if it["source"].lower() not in GEO_SOURCES:
                    continue
                if not GEO_KW.search(t) or GEO_EXCLUDE.search(t):
                    continue
            else:
                if NOT_MARKET_KW.search(t):
                    continue
                if is_gn and it["source"].lower() not in BIG_SOURCES:
                    continue
                if sec == "us" and it["source"] in KW_FILTERED and not MARKET_KW.search(t):
                    continue
                if it.pop("_he_kw", False) and not HE_MARKET_KW.search(t):
                    continue
                if it["source"] == "Seeking Alpha" and SA_NOISE.search(t):
                    continue
            bucket = "Google News" if is_gn else it["source"]
            cap = SRC_CAPS[sec].get(bucket, 2)
            if per_src.get(bucket, 0) >= cap:
                continue
            toks = norm_title(t)
            if is_dup(toks, kept_toks):
                continue
            kept_toks.append(toks)
            per_src[bucket] = per_src.get(bucket, 0) + 1
            it["lang"] = "he" if re.search(r"[\u0590-\u05ff]", t) else "en"
            it.pop("_gn", None)
            out.append(it)
            if len(out) >= CAPS[sec]:
                break
        sections[sec] = out

    payload = {
        "version": 1,
        "generated_at": datetime.now(JER).isoformat(),
        "windows_h": WINDOWS_H,
        "sections": sections,
        "sources_ok": ok,
        "sources_failed": failed,
    }
    tmp = OUT_FILE + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=1)
    os.replace(tmp, OUT_FILE)
    print(f"WROTE {OUT_FILE}: us={len(sections['us'])} il={len(sections['il'])} geo={len(sections['geo'])}"
          + (f" failed={failed}" if failed else ""))


if __name__ == "__main__":
    main()
